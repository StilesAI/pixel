class Font:
    def __init__(self, name, glyphs, height, line_height, upper_only=False):
        self.name = name
        self.height = height
        self.line_height = line_height
        self.upper_only = upper_only
        self.glyphs = {}
        for ch, rows in glyphs.items():
            w = max(len(r) for r in rows)
            a = np.zeros((len(rows), w), bool)
            for y, r in enumerate(rows):
                for x, c in enumerate(r):
                    a[y, x] = c == "#"
            self.glyphs[ch] = a

    def glyph(self, ch):
        if self.upper_only and ch not in self.glyphs:
            ch = ch.upper()
        g = self.glyphs.get(ch)
        if g is None:
            g = self.glyphs.get(ch.upper(), self.glyphs["?"])
        return g

    def measure(self, text, scale=1, spacing=1):
        w = 0
        for i, ch in enumerate(text):
            w += self.glyph(ch).shape[1] * scale
            if i < len(text) - 1:
                w += spacing * scale
        return w

    def mask(self, text, scale=1, spacing=1):
        """Bool array for a single line of text."""
        w = max(1, self.measure(text, scale, spacing))
        h = (self.line_height) * scale
        m = np.zeros((h, w), bool)
        x = 0
        for ch in text:
            g = self.glyph(ch)
            if scale > 1:
                g = np.kron(g, np.ones((scale, scale), bool))
            gh, gw = g.shape
            m[:gh, x:x + gw] |= g
            x += gw + spacing * scale
        return m


